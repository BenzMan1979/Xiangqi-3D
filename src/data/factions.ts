/** The character standing behind a piece. Pairs are assigned by the piece id's index ("red-r-1" → second rook). */
export function characterFor(faction: Faction, piece: Piece): Character {
  const slot = faction.roster[piece.type];
  if (!Array.isArray(slot)) return slot;
  const index = Number(piece.id.split('-')[2]) || 0;
  return slot[Math.min(index, 1)];
}

